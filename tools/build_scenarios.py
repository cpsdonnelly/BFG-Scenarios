#!/usr/bin/env python3
"""Merge catalogue/data/*.json into catalogue/scenarios.json and render catalogue/scenarios.md.

Source of truth: the per-publication files in catalogue/data/ (lists of entries)
and catalogue/shortlist.json. Run from the repo root: python3 tools/build_scenarios.py
"""
import glob, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "catalogue", "data")
TYPES = {"battle", "raid", "narrative", "campaign-linked", "tournament/matched", "small-game"}
REQUIRED = ["id", "title", "source", "pages", "author", "in_booklet", "type", "generic",
            "factions_required", "forces", "special_rules", "xr_dependencies", "xr_conflicts",
            "missing_or_unclear", "diagram", "ocr", "length", "notes"]
LISTS = ["special_rules", "xr_dependencies", "xr_conflicts", "missing_or_unclear"]


def load():
    entries = []
    for fn in sorted(glob.glob(os.path.join(DATA, "*.json"))):
        with open(fn, encoding="utf-8") as f:
            for e in json.load(f):
                e["_file"] = os.path.basename(fn)
                entries.append(e)
    return entries


def validate(entries):
    errs, ids = [], set()
    for e in entries:
        tag = f"{e.get('_file')}:{e.get('id')}"
        for k in REQUIRED:
            if k not in e:
                errs.append(f"{tag}: missing {k}")
        if e.get("id") in ids:
            errs.append(f"{tag}: duplicate id")
        ids.add(e.get("id"))
        if e.get("type") not in TYPES:
            errs.append(f"{tag}: bad type {e.get('type')}")
        if e.get("in_booklet") not in ("yes", "no", "variant"):
            errs.append(f"{tag}: bad in_booklet")
        if e.get("ocr") not in ("yes", "no", "partly"):
            errs.append(f"{tag}: bad ocr")
        if e.get("diagram") not in ("none", "simple", "complex"):
            errs.append(f"{tag}: bad diagram")
        for k in LISTS:
            if not isinstance(e.get(k), list):
                errs.append(f"{tag}: {k} must be a list")
        if isinstance(e.get("xr_conflicts"), list) and not e["xr_conflicts"]:
            errs.append(f"{tag}: xr_conflicts empty: write what was checked")
        blob = json.dumps(e, ensure_ascii=False)
        if "—" in blob:
            errs.append(f"{tag}: em dash")
    return errs


def cell(s):
    return str(s).replace("|", "/").replace("\n", " ")


def render_conflict(c):
    if isinstance(c, str):
        return c
    parts = [f"**{c['topic']}.**"]
    if c.get("source_text"):
        parts.append(f"Source: “{c['source_text']}”")
    if c.get("xr_text"):
        sec = f" ({c['xr_section']})" if c.get("xr_section") else ""
        parts.append(f"XR{sec}: “{c['xr_text']}”")
    if c.get("effect"):
        parts.append(f"Effect: {c['effect']}")
    return " ".join(parts)


def render(entries, shortlist):
    out = ["# Scenario catalogue", "",
           "Generated by `tools/build_scenarios.py` from `catalogue/data/*.json`. Do not edit by hand.", ""]
    out.append("## Shortlist")
    out.append("")
    if shortlist:
        out.append("Ranked. Reasons are one line each; the full entries follow.")
        out.append("")
        for i, s in enumerate(shortlist, 1):
            out.append(f"{i}. **{s['title']}** ({s['source']}). {s['reason']}")
    else:
        out.append("(Not yet written.)")
    out += ["", "## Summary table", "",
            "| id | Title | Source | Type | Generic | In booklet | OCR |", "|---|---|---|---|---|---|---|"]
    for e in entries:
        out.append("| " + " | ".join(cell(x) for x in [e["id"], e["title"], e["source"], e["type"],
                   e["generic"], e["in_booklet"], e["ocr"]]) + " |")
    out += ["", "## Entries", ""]
    group = None
    for e in entries:
        if e.get("group") != group:
            group = e.get("group")
            out += [f"### {group}", ""]
        out.append(f"#### {e['title']} (`{e['id']}`)")
        out.append("")
        out.append(f"*{e['source']}, {e['pages']}. Author: {e['author']}. Type: {e['type']}. "
                   f"Generic: {e['generic']}. Factions: {e['factions_required']}. In booklet: {e['in_booklet']}"
                   f"{' (' + e['booklet_note'] + ')' if e.get('booklet_note') else ''}. "
                   f"OCR: {e['ocr']}{' (' + e['ocr_note'] + ')' if e.get('ocr_note') else ''}. "
                   f"Diagram: {e['diagram']}. Rules text: {e['length']}.*")
        out.append("")
        out.append(e["summary"] if e.get("summary") else "")
        out.append("")
        out.append(f"**Forces.** {e['forces']}")
        out.append("")
        for label, key in [("Special rules", "special_rules"), ("XR and booklet rules relied on", "xr_dependencies")]:
            if e[key]:
                out.append(f"**{label}.** " + "; ".join(e[key]) + ".")
                out.append("")
        out.append("**Conflicts with XR.**")
        out.append("")
        for c in e["xr_conflicts"]:
            out.append("- " + render_conflict(c))
        out.append("")
        if e["missing_or_unclear"]:
            out.append("**Missing or unclear.**")
            out.append("")
            for m in e["missing_or_unclear"]:
                out.append("- " + m)
            out.append("")
        if e["notes"]:
            out.append("**Notes.** " + e["notes"])
            out.append("")
    return "\n".join(out)


def main():
    entries = load()
    errs = validate(entries)
    if errs:
        print("\n".join(errs))
        sys.exit(1)
    shortlist = []
    sl = os.path.join(ROOT, "catalogue", "shortlist.json")
    if os.path.exists(sl):
        shortlist = json.load(open(sl, encoding="utf-8"))
    clean = [{k: v for k, v in e.items() if k != "_file"} for e in entries]
    with open(os.path.join(ROOT, "catalogue", "scenarios.json"), "w", encoding="utf-8") as f:
        json.dump(clean, f, indent=1, ensure_ascii=False)
    with open(os.path.join(ROOT, "catalogue", "scenarios.md"), "w", encoding="utf-8") as f:
        f.write(render(entries, shortlist))
    print(f"{len(entries)} entries, shortlist {len(shortlist)}")


if __name__ == "__main__":
    main()
